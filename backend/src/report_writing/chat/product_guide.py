"""产品使用说明：事实草稿 + LLM 拟人化输出。"""

from __future__ import annotations

import re
from typing import Callable

InvokeFn = Callable[[str, str], str]

_USAGE_GUIDE_MESSAGE_RE = re.compile(
    r"^(使用说明|怎么用|如何使用|怎么用这个|产品说明|功能介绍|帮助说明)[\s？?。!！]*$",
    re.IGNORECASE,
)


def message_requests_usage_guide(text: str) -> bool:
    """口语/按钮：应走事实稿 + LLM 润色，而非泛聊。"""
    t = (text or "").strip()
    if not t:
        return False
    if _USAGE_GUIDE_MESSAGE_RE.match(t):
        return True
    if t in {"使用说明", "怎么用", "如何使用"}:
        return True
    return False


def _is_unconfigured_model_reply(text: str) -> bool:
    raw = (text or "").strip()
    return bool(raw) and ("未配置大模型" in raw or "接入模型后" in raw)


USAGE_GUIDE_DRAFT = """
智能文档协作 — 使用说明（事实稿，润色时须全部保留）

【一、你能做什么 · 怎么开始】
- 对话写文档：在聊天里说想写什么（如「以「建设美丽中国」为题写一份文档」），助手会引导定名、选写作方式、出目录、配要点、按章写作，并可导出 Word。
- 两条主路：
  1）有蓝本：选用/匹配已有蓝本 → 在文档窗口勾选章节 → 分析要点（如需要）→ 写作 → 导出。
  2）无蓝本：定好文档名 → 选「无蓝本」→ 可「依据模版」上传样板，或「自动生成大纲」→ 确认目录 → 生成/跳过写作要点 → 勾选章节写作 → 导出。
- 也可只问用法：点输入区上方「使用说明」，或直接说「怎么用」。
- 顶部可选机器人（影响提示词与绑定资源）；可不选，直接开写。
- 右侧「文档窗口」是目录、章节配置、正文与进度的主工作台；左侧对话负责意图与推进。

【二、各模块是干什么的】
- 对话区：说需求、点澄清卡、看过程与结果；不要当唯一编辑器。
- 文档窗口：当前这份文档的目录树、章节配置、写作要点、正文、阶段按钮（确认大纲、生成要点、写作等）；勾选章节后再点「分析/写作」只处理勾选范围。
- 蓝本库：存放可复用的文档结构（目录、章要点、写法约定）。有蓝本可直接开写；无蓝本写完后可「收录到蓝本库」，已有源蓝本可用「同步到蓝本库」回写改动。
- 要素库：存放可复用的「要素」信息（固定字段、说明、检索词、可引用的资料槽位等）。章节可关联要素，写作时按要素去检索与落笔；也可把文档里新出现的要素「收集」进个人要素库。
- 资料库 / 资料包：按「槽位」存放本任务要用的文件资料（上传、解析）。要素可引用槽位编号；开写前可新建/换绑资料包，不配也能写。
- 知识库：机器人可绑定的检索语料；有资料时检索更准，没有也能先写。（章节侧「关联知识库」已下线，资料请走要素文件或资料包。）
- 渲染模版 / Word 样式：控制导出 Word 的版式与样式；在导出前于输入区上方下拉选择（可选）。
- 机器人：一套提示词与资源绑定（蓝本/知识/样式等）；切换机器人会改变匹配与生成偏好。

【三、写文档全流程（推荐顺序）】
1. 开口：说明题目或类型，如「帮我写述职报告」或「以「××」为题写一份文档」。
2. 定名：确认文档叫什么（可点澄清卡「就叫××」，或说「名字叫××」）。
3. 选路：有蓝本 / 无蓝本；无蓝本再选「依据模版」或「自动生成大纲」。
4. 目录：生成或提取目录 → 在文档窗口检查、增删改 → 点「确认大纲并继续」。
5. 要点（可选）：自动起草各章写作要点与检索词，或跳过；可在章节配置里改。
6. 写作：在目录树勾选要写的章 → 点「写作」（或阶段条「开始写作」）；过程中文档窗口会锁定并定位到当前章。
7. 改稿：单章可重写、改配置、补要素；需要暂停可点暂停。
8. 沉淀（可选）：满意后收录/同步到蓝本库；要素可收集入库。
9. 导出：准备导出 Word，按需选渲染模版与 Word 样式。

【常用说法】
- 「以「××」为题写一份文档」「看看有哪些蓝本」「不用蓝本 / 自动生成大纲」「我有模版」「帮我生成目录」「生成写作要点」「导出 Word」
"""


def build_usage_guide_reply(invoke: InvokeFn | None) -> str:
    draft = USAGE_GUIDE_DRAFT.strip()
    if not invoke:
        return _fallback_plain_guide()
    system = (
        "你是智能文档协作助手「小墨」，要把「事实稿」改写成给用户看的使用说明。"
        "要求：口语、亲切、像同事介绍产品；分段清晰可用短标题，但不要 Markdown 符号（#、**）。"
        "结构必须覆盖：能做什么/怎么开始、各模块用途、写文档全流程；禁止编造功能。"
        "必须保留事实稿里的全部能力点与模块（对话、文档窗口、蓝本库、要素库、资料包、知识库、渲染/样式、机器人）。"
        "篇幅适中（约 500～900 字），结尾可加一句「随时在对话框里说你想写什么」。"
        "只输出正文。"
    )
    user = f"事实稿：\n{draft}\n\n请润色后输出使用说明。"
    try:
        text = str(invoke(system, user) or "").strip()
        if _is_unconfigured_model_reply(text):
            return _fallback_plain_guide()
        if len(text) >= 120 and "事实稿" not in text[:80]:
            return text[:4500]
    except Exception:
        pass
    return _fallback_plain_guide()


def _fallback_plain_guide() -> str:
    return (
        "你好，我是小墨。这里可以按对话写文档，右侧文档窗口管目录和正文。\n\n"
        "一、怎么用：直接说想写什么；有蓝本就选用后勾章开写，没有就定名→选无蓝本→出目录→确认→配要点（可跳过）→勾章写作→导出 Word。\n\n"
        "二、模块：蓝本库存可复用目录与写法；要素库存固定信息与检索约定，章可关联；"
        "资料包按槽位放文件；知识库给机器人检索；渲染模版/Word 样式管导出版式；机器人切换绑定资源。\n\n"
        "三、流程：定名 → 选有/无蓝本 → 确认目录 →（可选）要点 → 勾选章节写作 → 改稿 →（可选）收录蓝本 → 导出。\n\n"
        "直接跟我说你想写什么就行。"
    )
